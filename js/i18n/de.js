export function t(key, vars = {}) {
  const s = de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Plural: sucht key.zero (bei 0, falls vorhanden), key.one oder key.other. */
export function tn(key, n, vars = {}) {
  const form = n === 0 && de[`${key}.zero`] ? 'zero' : n === 1 ? 'one' : 'other';
  return t(`${key}.${form}`, { n, ...vars });
}

export function formatDate(ts) {
  return new Intl.DateTimeFormat('de-DE', { day: 'numeric', month: 'long', year: 'numeric' }).format(new Date(ts));
}
